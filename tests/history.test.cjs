'use strict';
const {test} = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const storage = require('../browser/storage.cjs');
const {HistoryService, decode} = require('../browser/history.cjs');

function fixture(t, options = {}) {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'nox-history-'));
  t.after(() => fs.rmSync(directory, {recursive: true, force: true}));
  const file = path.join(directory, 'history.json'), events = [];
  const setup = {file, getIdentities: () => ['personal', 'work'], onChange: event => events.push(event), ...options};
  const service = new HistoryService(setup); service.open();
  return {service, file, events, reopen: () => { const next = new HistoryService(setup); next.open(); return next; }};
}
test('history persists stable page/visit IDs, title updates and repeated visits across restart', t => {
  const {service, reopen, events} = fixture(t, {now: () => 1000});
  const first = service.record('personal', {url: 'https://example.com', title: 'First title', transition: 'typed'});
  const second = service.record('personal', {url: 'https://example.com/', title: 'Latest title', visitTime: 2000, referringVisitId: first.visit.visitId});
  service.record('personal', {url: 'https://example.com/', title: 'Older imported title', visitTime: 500});
  assert.equal(second.item.id, first.item.id); assert.notEqual(first.visit.visitId, second.visit.visitId);
  assert.equal(service.search('personal')[0].title, 'Latest title');
  assert.equal(service.updateTitle('personal', 'https://example.com/', 'Committed title'), true);
  assert.equal(service.updateTitle('personal', 'https://missing.test/', 'Ignored'), false);
  const restored = reopen(), page = restored.search('personal')[0], visits = restored.getVisits('personal', 'https://example.com/');
  assert.equal(page.id, first.item.id); assert.equal(page.visitCount, 3); assert.equal(page.typedCount, 1); assert.equal(page.lastVisitTime, 2000); assert.equal(page.title, 'Committed title');
  assert.deepEqual(new Set(visits.map(visit => visit.visitId)), new Set([first.visit.visitId, second.visit.visitId, visits.find(visit => visit.visitTime === 500).visitId]));
  assert.equal(visits[0].referringVisitId, first.visit.visitId);
  assert.equal(events.filter(event => event.type === 'visited').length, 3);
  assert.equal(events.filter(event => event.type === 'title').length, 1);
});
test('history queries, referrers and deletion stay within the exact browser identity', t => {
  const {service, events} = fixture(t);
  const personal = service.record('personal', {url: 'https://same.example/', title: 'Personal'});
  const work = service.record('work', {url: 'https://same.example/', title: 'Work'});
  assert.notEqual(personal.item.id, work.item.id);
  assert.throws(() => service.record('work', {url: 'https://second.example/', referringVisitId: personal.visit.visitId}), /referring visit/);
  assert.throws(() => service.search('WORK'), error => error.code === 'NOT_FOUND');
  assert.throws(() => service.clear('unknown'), /Unknown browser identity/);
  const results = service.search('personal'); results[0].title = 'Mutated caller copy';
  assert.equal(service.search('personal')[0].title, 'Personal');
  assert.deepEqual(service.clear('personal'), {removedVisits: 1, removedUrls: 1});
  assert.equal(service.search('work')[0].title, 'Work');
  assert.deepEqual(events.findLast(event => event.type === 'removed').urls, []);
  assert.equal(events.findLast(event => event.type === 'removed').identity, 'personal');
});
test('range deletion removes individual visits, preserves surviving page IDs and repairs referrers', t => {
  const {service, reopen, events} = fixture(t);
  const first = service.record('personal', {url: 'https://example.com/', visitTime: 100, transition: 'typed'});
  const second = service.record('personal', {url: 'https://example.com/', visitTime: 200});
  service.record('personal', {url: 'https://referrer.example/', visitTime: 300, referringVisitId: first.visit.visitId});
  assert.deepEqual(service.search('personal', {startTime: 100, endTime: 200}), []);
  assert.deepEqual(service.deleteRange('personal', {startTime: 100, endTime: 200}), {removedVisits: 1, removedUrls: 0});
  assert.equal(service.getVisits('personal', 'https://example.com/')[0].visitId, second.visit.visitId);
  assert.equal(service.search('personal', {text: 'example.com'})[0].id, first.item.id);
  assert.equal(service.search('personal', {text: 'example.com'})[0].typedCount, 0);
  assert.equal(service.getVisits('personal', 'https://referrer.example/')[0].referringVisitId, '0');
  assert.deepEqual(events.findLast(event => event.type === 'removed').urls, []);
  assert.deepEqual(service.deleteUrl('personal', 'https://example.com'), {removedVisits: 1, removedUrls: 1});
  assert.equal(reopen().search('personal').length, 1);
});
test('query terms, paging, time ranges and unlimited defaults retain complete results', t => {
  const {service, file} = fixture(t);
  const items = Array.from({length: 1250}, (_, index) => ({id: `page-${index}`, identity: 'personal', url: `https://example.com/${index}`, title: `Topic ${index}`, visits: [{visitId: `visit-${index}`, visitTime: index + 1, transition: 'link', referringVisitId: '0'}]}));
  storage.write(file, {version: 1, items, preferences: []}, decode); service.open();
  assert.equal(service.search('personal').length, 1250);
  assert.equal(service.search('personal', {text: 'TOPIC HTTPS'}).length, 1250);
  const page = service.query('personal', {offset: 100, limit: 80});
  assert.equal(page.total, 1250); assert.equal(page.items.length, 80); assert.equal(page.items[0].lastVisitTime, 1150); assert.equal(page.hasMore, true);
  assert.deepEqual(service.query('personal', {offset: 1250, limit: 80}), {items: [], total: 1250, offset: 1250, hasMore: false});
  assert.equal(service.search('personal', {startTime: 100, endTime: 101})[0].lastVisitTime, 100);
  assert.deepEqual(service.search('personal', {maxResults: 0}), []);
  assert.throws(() => service.query('personal', {offset: -1}), /nonnegative/);
  assert.throws(() => service.query('personal', {limit: null}), /nonnegative/);
  assert.throws(() => service.query('personal', {startTime: 200, endTime: 100}), /ends before/);
});
test('recording and retention are independent per identity and persist without a hidden default cap', t => {
  let now = 10 * 86400000;
  const {service, reopen, events} = fixture(t, {now: () => now});
  service.record('personal', {url: 'https://old.example/', visitTime: 1});
  service.record('personal', {url: 'https://edge.example/', visitTime: 8 * 86400000});
  service.record('work', {url: 'https://old.example/', visitTime: 1});
  assert.equal(service.settings('personal').retentionDays, null);
  service.configure('personal', {retentionDays: 2, recording: false});
  assert.deepEqual(service.record('personal', {url: 'https://paused.example/'}), {recorded: false, reason: 'recording-disabled'});
  assert.equal(service.updateTitle('personal', 'https://edge.example/', 'Private title while paused'), false);
  assert.equal(service.search('personal')[0].title, 'https://edge.example/');
  assert.equal(service.search('personal').length, 1); assert.equal(service.search('work').length, 1);
  assert.equal(reopen().settings('personal').recording, false);
  service.configure('personal', {recording: true});
  assert.deepEqual(service.record('personal', {url: 'https://too-old.example/', visitTime: 1}), {recorded: false, reason: 'outside-retention'});
  now++;
  assert.deepEqual(service.prune('personal'), {removedVisits: 1, removedUrls: 1});
  assert.equal(events.filter(event => event.type === 'visited').length, 3);
});
test('failed history save emits no visited event, preserves bytes and supports explicit reopen/retry', t => {
  const {service, file, events} = fixture(t);
  service.record('personal', {url: 'https://saved.example/'});
  const bytes = fs.readFileSync(file), count = events.filter(event => event.type === 'visited').length;
  const original = storage.write;
  t.mock.method(storage, 'write', () => { throw Object.assign(new Error('Synthetic disk full'), {code: 'ENOSPC'}); });
  assert.throws(() => service.record('personal', {url: 'https://failed.example/'}), /disk full/);
  assert.equal(service.status, 'error'); assert.deepEqual(fs.readFileSync(file), bytes);
  assert.equal(events.filter(event => event.type === 'visited').length, count);
  storage.write = original; service.open();
  assert.equal(service.search('personal').length, 1);
  service.record('personal', {url: 'https://retry.example/'}); assert.equal(service.search('personal').length, 2);
});
test('history refuses a stale writer and observer failures cannot undo successful durable writes', t => {
  const {service, reopen, file} = fixture(t);
  service.record('personal', {url: 'https://first.example/'});
  const stale = reopen();
  service.subscribe(() => { throw new Error('Synthetic observer failure'); });
  service.record('personal', {url: 'https://second.example/'});
  const bytes = fs.readFileSync(file);
  assert.throws(() => stale.record('personal', {url: 'https://stale.example/'}), error => error.code === 'STALE_PREVIEW');
  assert.deepEqual(fs.readFileSync(file), bytes); stale.open(); assert.equal(stale.search('personal').length, 2);
});
test('history recovery preserves corrupt bytes and future versions never downgrade to a backup', t => {
  const {service, file, reopen} = fixture(t);
  service.record('personal', {url: 'https://previous.example/'}); service.record('personal', {url: 'https://latest.example/'});
  const previous = fs.readFileSync(`${file}.previous`);
  fs.writeFileSync(file, '{broken'); const opened = service.open();
  assert.equal(opened.status, 'recovery'); assert.throws(() => service.search('personal'), /explicitly recovered/);
  fs.writeFileSync(file, '{changed'); assert.throws(() => service.recover(opened.preview), error => error.code === 'STALE_PREVIEW');
  service.open(); const recovered = service.recover();
  assert.equal(fs.readFileSync(recovered.preserved, 'utf8'), '{changed'); assert.deepEqual(fs.readFileSync(file), previous);
  assert.equal(service.search('personal').length, 1);
  const future = '{"version":2,"items":[],"preferences":[],"future":true}'; fs.writeFileSync(file, future);
  assert.throws(() => service.open(), error => error.code === 'UNSUPPORTED_VERSION');
  assert.throws(() => service.recover(), /inspect a recoverable/);
  assert.throws(() => reopen(), error => error.code === 'UNSUPPORTED_VERSION');
  assert.equal(fs.readFileSync(file, 'utf8'), future); assert.deepEqual(fs.readFileSync(`${file}.previous`), previous);
});
test('history preserves unknown metadata, rejects credential-bearing URLs and closes subscriptions', t => {
  const {service, file, events} = fixture(t);
  service.record('personal', {url: 'https://example.com/'});
  const raw = storage.parse(fs.readFileSync(file)); raw.future = {retained: true}; raw.items[0].extra = ['kept']; raw.items[0].visits[0].detail = {future: 1};
  fs.writeFileSync(file, JSON.stringify(raw)); service.open(); service.updateTitle('personal', 'https://example.com/', 'Changed');
  const stored = storage.parse(fs.readFileSync(file)); assert.deepEqual(stored.future, raw.future); assert.deepEqual(stored.items[0].extra, ['kept']); assert.deepEqual(stored.items[0].visits[0].detail, {future: 1});
  assert.equal(service.search('personal')[0].extra, undefined);
  for (const address of ['https://user:secret@example.com/', 'javascript:alert(1)', 'file:///private', 'about:blank']) assert.throws(() => service.record('personal', {url: address}), /HTTP/);
  let called = 0; const unsubscribe = service.subscribe(() => called++); unsubscribe(); service.record('personal', {url: 'https://later.example/'}); assert.equal(called, 0);
  service.dispose(); const before = events.length;
  assert.throws(() => service.record('personal', {url: 'https://after-close.example/'}), error => error.code === 'DISPOSED'); assert.equal(events.length, before);
});
